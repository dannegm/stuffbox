-- -----------------------------------------------------------------------------
-- Invite RPCs
-- -----------------------------------------------------------------------------
-- Mirrors bins' get_bin_access(): a security-definer RPC lets a non-member
-- resolve a single invite by its (unguessable) token without a public SELECT
-- policy that would expose every workspace's invites to any authenticated user.

-- Read-only landing check (app/invite/[token] — bot-safe, no side effects)
create or replace function stuffbox.get_invite_by_token(p_token text)
returns table(invite_id text, workspace_id text, workspace_name text, valid boolean)
security definer stable language sql as $$
  select
    i.id,
    i.workspace_id,
    w.name,
    (i.uses_count < i.max_uses and now() < i.expires_at)
  from stuffbox.workspace_invites i
  join stuffbox.workspaces w on w.id = i.workspace_id
  where i.token = p_token;
$$;

-- "Unirse" — atomic claim (increment + validity check in one statement) then join
create or replace function stuffbox.claim_workspace_invite(p_token text)
returns table(workspace_id text)
security definer language plpgsql as $$
declare
  v_workspace_id text;
begin
  update stuffbox.workspace_invites
  set uses_count = uses_count + 1
  where token = p_token
    and uses_count < max_uses
    and now() < expires_at
  returning stuffbox.workspace_invites.workspace_id into v_workspace_id;

  if v_workspace_id is null then
    raise exception 'Invite is invalid, expired, or exhausted';
  end if;

  insert into stuffbox.workspace_members (workspace_id, user_id)
  values (v_workspace_id, auth.uid())
  on conflict do nothing;

  return query select v_workspace_id;
end;
$$;

grant execute on function stuffbox.get_invite_by_token(text) to authenticated;
grant execute on function stuffbox.claim_workspace_invite(text) to authenticated;

-- A fresh visitor following an /invite/[token] link has no session yet, so
-- the landing lookup above runs as anon — needs its own narrow grant rather
-- than the blanket authenticated/service_role one below. claim stays
-- authenticated-only: it never runs until after the OTP verify establishes
-- a session.
grant execute on function stuffbox.get_invite_by_token(text) to anon;


-- -----------------------------------------------------------------------------
-- Location price rollup
-- -----------------------------------------------------------------------------
-- Recursive sum of purchase_price across every item in a location's subtree
-- (nested boxes included, any depth). Plain invoker rights (no security
-- definer) — the underlying RLS on locations/items already scopes this to
-- what the caller can see, so an out-of-workspace id just sums to 0 instead
-- of leaking anything.

create or replace function stuffbox.location_total_price(p_location_id text)
returns numeric
language sql
stable
as $$
  with recursive subtree as (
    select id from stuffbox.locations where id = p_location_id
    union all
    select l.id from stuffbox.locations l
    join subtree s on l.parent_id = s.id
  )
  select coalesce(sum(i.purchase_price), 0)
  from stuffbox.items i
  where i.location_id in (select id from subtree);
$$;

grant execute on function stuffbox.location_total_price(text) to authenticated;


-- -----------------------------------------------------------------------------
-- Workspace search
-- -----------------------------------------------------------------------------
-- Resolves only the ordered (kind, id) pairs + total_count for a workspace
-- search — the one thing that needs real SQL (union across two tables, a
-- recursive ancestor walk for the house filter, and a single shared count).
-- The app fetches full item/location rows for this page's ids separately via
-- plain direct-client selects (same shape as itemsAtLocationQuery /
-- locationChildrenQuery), so search results carry the same photos/tags/
-- fields as their native list views instead of a stripped-down shape.
--
-- Plain invoker rights (no security definer), same pattern as
-- location_total_price above — RLS on locations/items already scopes this to
-- what the caller can see. Type only applies to locations (items have no
-- `type` column) and tags only apply to items (locations have no tags), so
-- each side excludes itself entirely when the other's filter is active.
--
-- Name matching combines exact substring (ilike) with pg_trgm word_similarity
-- for typo tolerance ("macbuc" → "MacBook") — ilike stays as the guaranteed
-- match (trigram similarity is unreliable for very short queries like SKUs),
-- word_similarity only adds the fuzzy net on top. word_similarity (not plain
-- similarity) because it scores the best-matching word/substring within the
-- name rather than the whole string, since names are usually longer than the
-- query. Results rank by word_similarity when a query is present, else by
-- name (plain alphabetical browse).
create or replace function stuffbox.search_workspace(
  p_workspace_id text,
  p_query        text default null,
  p_tag_ids      uuid[] default null,
  p_type_ids     text[] default null,
  p_packed       boolean default null,
  p_house_ids    text[] default null,
  p_limit        int default 25,
  p_offset       int default 0
)
returns table (
  kind        text,
  id          text,
  total_count bigint
)
language sql
stable
as $$
  with recursive location_roots as (
    select l.id, l.id as root_id
    from stuffbox.locations l
    where l.parent_id is null and l.workspace_id = p_workspace_id
    union all
    select l.id, lr.root_id
    from stuffbox.locations l
    join location_roots lr on l.parent_id = lr.id
    where l.workspace_id = p_workspace_id
  ),
  matched_locations as (
    select 'location'::text as kind, l.id, l.name
    from stuffbox.locations l
    join location_roots lr on lr.id = l.id
    where l.workspace_id = p_workspace_id
      and p_tag_ids is null
      and (
        p_query is null
        or l.name ilike '%' || p_query || '%'
        or word_similarity(p_query, l.name) > 0.3
      )
      and (p_type_ids is null or l.type = any(p_type_ids))
      and (p_packed is null or (l.active_move_id is not null) = p_packed)
      and (p_house_ids is null or lr.root_id = any(p_house_ids))
  ),
  matched_items as (
    select 'item'::text as kind, i.id, i.name
    from stuffbox.items i
    join location_roots lr on lr.id = i.location_id
    where i.workspace_id = p_workspace_id
      and p_type_ids is null
      and (
        p_query is null
        or i.name ilike '%' || p_query || '%'
        or word_similarity(p_query, i.name) > 0.3
      )
      and (p_packed is null or (i.active_move_id is not null) = p_packed)
      and (p_house_ids is null or lr.root_id = any(p_house_ids))
      and (
        p_tag_ids is null
        or exists (
          select 1 from stuffbox.item_tags it
          where it.item_id = i.id and it.tag_id = any(p_tag_ids)
        )
      )
  ),
  combined as (
    select * from matched_locations
    union all
    select * from matched_items
  )
  select c.kind, c.id, count(*) over() as total_count
  from combined c
  order by
    case when p_query is not null then word_similarity(p_query, c.name) end desc nulls last,
    c.name
  limit p_limit offset p_offset;
$$;

grant execute on function stuffbox.search_workspace(text, text, uuid[], text[], boolean, text[], int, int) to authenticated;


-- -----------------------------------------------------------------------------
-- Triggers
-- -----------------------------------------------------------------------------
-- Account provisioning (profile + workspace + owner membership + seeded
-- option_lists) is NOT here — it's app code. See src/services/provision-account.js.
-- No structural validation on moves either (e.g. "endpoints must be roots") —
-- that's a mutationFn's job if/when it's actually needed. What's left is only
-- the audit log, which has to hold regardless of which code path wrote the row.

-- movement_log: written on item location/move changes, never by app logic.
-- security definer — movement_log has no member INSERT policy on purpose
-- (read-only for members), so the trigger itself needs elevated rights to
-- write the audit row regardless of the calling user's own grants.
create or replace function stuffbox.log_item_movement()
returns trigger
language plpgsql
security definer
as $$
begin
  if NEW.location_id is distinct from OLD.location_id
     or NEW.active_move_id is distinct from OLD.active_move_id then
    insert into stuffbox.movement_log
      (workspace_id, entity_type, entity_id, from_location_id, to_location_id, move_id)
    values
      (NEW.workspace_id, 'item', NEW.id, OLD.location_id, NEW.location_id, NEW.active_move_id);
  end if;
  return NEW;
end;
$$;

create trigger on_item_location_change
  after update on stuffbox.items
  for each row execute function stuffbox.log_item_movement();

-- movement_log: written on location parent/move changes (transfer/pack/unpack)
-- security definer — same reason as log_item_movement() above.
create or replace function stuffbox.log_location_movement()
returns trigger
language plpgsql
security definer
as $$
begin
  if NEW.parent_id is distinct from OLD.parent_id
     or NEW.active_move_id is distinct from OLD.active_move_id then
    insert into stuffbox.movement_log
      (workspace_id, entity_type, entity_id, from_location_id, to_location_id, move_id)
    values
      (NEW.workspace_id, 'location', NEW.id, OLD.parent_id, NEW.parent_id, NEW.active_move_id);
  end if;
  return NEW;
end;
$$;

create trigger on_location_parent_change
  after update on stuffbox.locations
  for each row execute function stuffbox.log_location_movement();


