-- Helper: is auth.uid() a member (or owner) of this workspace? security
-- definer avoids recursive RLS. Owner is always also a workspace_members row
-- (app code inserts it alongside the workspace itself — see
-- src/services/provision-account.js), so this one check covers both.
create or replace function stuffbox.is_workspace_member(p_workspace_id text, p_user_id uuid)
returns boolean as $$
  select exists (
    select 1 from stuffbox.workspace_members
    where workspace_id = p_workspace_id and user_id = p_user_id
  );
$$ language sql security definer stable;

-- Helper: mirrors bins' requesting_user_is_admin() — security definer stable
create or replace function stuffbox.requesting_user_is_admin()
returns boolean as $$
  select coalesce(
    (select is_super_admin from stuffbox.profiles where uuid = auth.uid()),
    false
  );
$$ language sql security definer stable;

