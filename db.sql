-- -----------------------------------------------------------------------------
-- Schema
-- -----------------------------------------------------------------------------

create schema if not exists stuffbox;


-- -----------------------------------------------------------------------------
-- Extensions
-- -----------------------------------------------------------------------------
-- pg_trgm: trigram similarity, backing the fuzzy/typo-tolerant name match in
-- stuffbox.search_workspace (word_similarity) and doubling as an ilike
-- '%...%' accelerator for the GIN indexes below.
create extension if not exists pg_trgm;


-- -----------------------------------------------------------------------------
-- ID strategy
-- -----------------------------------------------------------------------------
-- Two kinds of primary key in this schema:
-- - text nanoid(8), generated client-side (JS `nanoid()`) and sent by the app
--   on insert — reserved for the entities that appear directly in app routes
--   and QR deep links: workspaces, locations, moves, items.
-- - uuid, generated by Postgres (`gen_random_uuid()` default) — every other
--   table, the conventional default. profiles is the one exception: its uuid
--   PK is not generated, it mirrors auth.users.id.
--
-- Account provisioning on signup (profile + workspace + owner membership +
-- seeded option_lists) is app code, not a DB trigger — see
-- src/services/provision-account.js. That's also why workspaces.id no longer
-- needs a SQL-side nanoid generator: the client that creates the workspace
-- generates its id, same as every other nanoid table.


-- -----------------------------------------------------------------------------
-- Tablas
-- -----------------------------------------------------------------------------

-- Mirrors auth.users; password never stored here — Supabase Auth owns it
create table stuffbox.profiles (
  uuid            uuid primary key,                    -- = auth.users.id
  name            text not null,
  email           text not null,                        -- mirror, set at signup
  gender          text not null,                         -- random@signup, editable; feeds DiceBear
  avatar_seed     text not null,
  color           text not null default '#e67e22',       -- single color, no light/dark split
  is_super_admin  boolean not null default false,        -- app-wide admin, DB-only editable
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- Collaboration container; auto-created per user on signup
-- id: nanoid(8), client-generated — appears in app/workspace/[id]
create table stuffbox.workspaces (
  id          text primary key,
  name        text not null,
  color       text,                                 -- nullable; falls back to a client-side hash (workspace-color.js) until set
  owner_id    uuid not null references stuffbox.profiles(uuid),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Owner is also inserted here on workspace creation, so membership is a
-- single check with no special-casing of the owner.
create table stuffbox.workspace_members (
  workspace_id  text not null references stuffbox.workspaces(id) on delete cascade,
  user_id       uuid not null references stuffbox.profiles(uuid),
  joined_at     timestamptz not null default now(),
  primary key (workspace_id, user_id)
);

-- Shareable link, no email flow. id is a plain uuid (never routed by itself —
-- the invite is looked up by `token`, see the RPCs below).
create table stuffbox.workspace_invites (
  id          uuid primary key default gen_random_uuid(),
  workspace_id text not null references stuffbox.workspaces(id) on delete cascade,
  token       text not null unique,
  max_uses    int not null default 1,
  uses_count  int not null default 0,
  expires_at  timestamptz not null default (now() + interval '7 days'),
  invited_by  uuid not null references stuffbox.profiles(uuid),
  created_at  timestamptz not null default now()
);

-- Generic unbounded tree: house/room/closet/shelf/drawer/warehouse/box are
-- all nodes; box = type='box'; multiple roots = multiple houses; boxes nest.
-- active_move_id references moves, created further below — FK added after.
-- id: nanoid(8), client-generated — appears in app/location/[id] and app/l/[id]
create table stuffbox.locations (
  id              text primary key,
  workspace_id    text not null references stuffbox.workspaces(id) on delete cascade,
  parent_id       text references stuffbox.locations(id) on delete cascade,
  name            text not null,
  type            text not null,                         -- free text
  icon            jsonb,                                  -- {library, name}
  lat             double precision,                       -- meaningful on roots for routes
  lng             double precision,
  active_move_id  text,                                   -- set when packed; FK added below
  ai_summary      text,                                   -- cached, regenerable
  is_container    boolean not null default false,          -- defaults true for box/shelf/toolbox/baggage (app-derived from type, not DB-enforced)
  is_item         boolean not null default false,          -- lets this location also appear in the swipe/rate deck, like an item
  description     text,
  is_fragile      boolean not null default false,
  storage_orientation text,                                -- ref option_lists(field='orientation'), no hard FK
  sentimental_value   smallint,                             -- 1-5, hearts
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- Route geometry NOT stored — computed live client-side. The plan's model
-- has origin/destination as root locations (house/warehouse), but that's not
-- DB-enforced — no constraint here blocks e.g. a same-building floor-to-floor
-- move if the app ever wants to allow one.
-- id: nanoid(8), client-generated — appears in app/move/[id]
create table stuffbox.moves (
  id                      text primary key,
  workspace_id            text not null references stuffbox.workspaces(id) on delete cascade,
  name                    text not null,
  origin_location_id      text not null references stuffbox.locations(id),
  destination_location_id text not null references stuffbox.locations(id),
  route_type              text not null default 'land',   -- 'land' | 'air'
  status                  text not null default 'planning', -- app-defined, not DB-constrained
  cost                    numeric,                        -- null = N/A until set via the summary box's edit button
  started_at              date,                            -- set alongside estimated_completion_at when status -> in_transit
  estimated_completion_at date,                            -- the deadline asked for in the same dialog as started_at
  completed_at            date,                            -- auto-set to today when status -> done
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now()
);

alter table stuffbox.locations
  add constraint fk_locations_active_move
  foreign key (active_move_id) references stuffbox.moves(id) on delete set null;

