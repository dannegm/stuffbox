create schema if not exists stuffbox;


-- -----------------------------------------------------------------------------
-- Extensions
-- -----------------------------------------------------------------------------
-- pg_trgm: trigram similarity, backing the fuzzy/typo-tolerant name match in
-- stuffbox.search_workspace (word_similarity) and doubling as an ilike
-- '%...%' accelerator for the GIN indexes below.
create extension if not exists pg_trgm;


-- -----------------------------------------------------------------------------
-- ID strategy
-- -----------------------------------------------------------------------------
-- Two kinds of primary key in this schema:
-- - text nanoid(8), generated client-side (JS `nanoid()`) and sent by the app
--   on insert — reserved for the entities that appear directly in app routes
--   and QR deep links: workspaces, locations, moves, items.
-- - uuid, generated by Postgres (`gen_random_uuid()` default) — every other
--   table, the conventional default. profiles is the one exception: its uuid
--   PK is not generated, it mirrors auth.users.id.
--
-- Account provisioning on signup (profile + workspace + owner membership +
-- seeded option_lists) is app code, not a DB trigger — see
-- src/services/provision-account.js. That's also why workspaces.id no longer
-- needs a SQL-side nanoid generator: the client that creates the workspace
-- generates its id, same as every other nanoid table.


