-- Helper: is auth.uid() a member (or owner) of this workspace? security
-- definer avoids recursive RLS. Owner is always also a workspace_members row
-- (app code inserts it alongside the workspace itself — see
-- src/services/provision-account.js), so this one check covers both.
create or replace function stuffbox.is_workspace_member(p_workspace_id text, p_user_id uuid)
returns boolean as $$
  select exists (
    select 1 from stuffbox.workspace_members
    where workspace_id = p_workspace_id and user_id = p_user_id
  );
$$ language sql security definer stable;

-- Helper: mirrors bins' requesting_user_is_admin() — security definer stable
create or replace function stuffbox.requesting_user_is_admin()
returns boolean as $$
  select coalesce(
    (select is_super_admin from stuffbox.profiles where uuid = auth.uid()),
    false
  );
$$ language sql security definer stable;

-- Helper: does this workspace's 'collaborationSettings' value allow regular
-- members (not just the owner) to create invite links? Missing key/value
-- coalesces to false — the safe default until an owner explicitly turns it on.
create or replace function stuffbox.workspace_allows_member_invites(p_workspace_id text)
returns boolean as $$
  select coalesce(
    (
      select (value->>'allowMemberInvites')::boolean
      from stuffbox.workspace_settings
      where workspace_id = p_workspace_id and key = 'collaborationSettings'
    ),
    false
  );
$$ language sql security definer stable;

-- Helper: same shape, for "can regular members remove other members?" —
-- removing the owner's own row is still blocked elsewhere regardless of this
-- setting (see the workspace_members delete policy below).
create or replace function stuffbox.workspace_allows_member_removal(p_workspace_id text)
returns boolean as $$
  select coalesce(
    (
      select (value->>'allowMemberRemove')::boolean
      from stuffbox.workspace_settings
      where workspace_id = p_workspace_id and key = 'collaborationSettings'
    ),
    false
  );
$$ language sql security definer stable;

-- Helper: same shape, for "can regular members edit the non-collaboration
-- settings (name/color, map default)?" — the collaboration section itself
-- and deleting the workspace stay owner-only regardless of this setting.
create or replace function stuffbox.workspace_allows_member_edit_settings(p_workspace_id text)
returns boolean as $$
  select coalesce(
    (
      select (value->>'allowMemberEditSettings')::boolean
      from stuffbox.workspace_settings
      where workspace_id = p_workspace_id and key = 'collaborationSettings'
    ),
    false
  );
$$ language sql security definer stable;

-- profiles
create policy "profiles: self access"
  on stuffbox.profiles for select
  using (uuid = auth.uid());

create policy "profiles: shared workspace visibility"
  on stuffbox.profiles for select
  using (
    exists (
      select 1
      from stuffbox.workspace_members mine
      join stuffbox.workspace_members theirs on theirs.workspace_id = mine.workspace_id
      where mine.user_id = auth.uid() and theirs.user_id = profiles.uuid
    )
  );

create policy "profiles: admin full access"
  on stuffbox.profiles for all
  using (stuffbox.requesting_user_is_admin())
  with check (stuffbox.requesting_user_is_admin());

create policy "profiles: owner can insert"
  on stuffbox.profiles for insert
  with check (uuid = auth.uid());

create policy "profiles: owner can update"
  on stuffbox.profiles for update
  using (uuid = auth.uid())
  with check (uuid = auth.uid() and is_super_admin = false);

-- workspaces (member WITH CHECK also allows owner_id = auth.uid() so the
-- owner can insert the very first row, before any workspace_members exists;
-- deleting the entire workspace, which cascades to everything it contains,
-- is owner-only; updating is owner-only unless collaborationSettings.
-- allowMemberEditSettings opts regular members in — select/insert stay open
-- to any member as before)
create policy "workspaces: member select"
  on stuffbox.workspaces for select
  using (stuffbox.is_workspace_member(id, auth.uid()));

create policy "workspaces: member insert"
  on stuffbox.workspaces for insert
  with check (owner_id = auth.uid() or stuffbox.is_workspace_member(id, auth.uid()));

create policy "workspaces: owner or allowed member update"
  on stuffbox.workspaces for update
  using (stuffbox.is_workspace_member(id, auth.uid()))
  with check (
    owner_id = auth.uid()
    or (
      stuffbox.is_workspace_member(id, auth.uid())
      and stuffbox.workspace_allows_member_edit_settings(id)
    )
  );

create policy "workspaces: owner delete"
  on stuffbox.workspaces for delete
  using (owner_id = auth.uid());

create policy "workspaces: admin full access"
  on stuffbox.workspaces for all
  using (stuffbox.requesting_user_is_admin())
  with check (stuffbox.requesting_user_is_admin());

-- workspace_members (insert allows self-join, which is only reachable via a
-- valid claim_workspace_invite() call — see RPCs below; delete restricted to
-- the workspace owner or the member removing themself, per the plan — and no
-- clause below may ever target the owner's own row: an owner can only leave
-- by deleting the whole workspace, never by deleting their own membership)
create policy "workspace_members: member select"
  on stuffbox.workspace_members for select
  using (stuffbox.is_workspace_member(workspace_id, auth.uid()));

create policy "workspace_members: self insert"
  on stuffbox.workspace_members for insert
  with check (user_id = auth.uid());

-- owner, self, or (when the workspace's collaborationSettings.allowMemberRemove
-- is on) any other member removing someone who isn't the owner
create policy "workspace_members: owner, self, or allowed member delete"
  on stuffbox.workspace_members for delete
  using (
    not exists (
      select 1 from stuffbox.workspaces w
      where w.id = workspace_id and w.owner_id = workspace_members.user_id
    )
    and (
      user_id = auth.uid()
      or exists (
        select 1 from stuffbox.workspaces w
        where w.id = workspace_id and w.owner_id = auth.uid()
      )
      or (
        stuffbox.workspace_allows_member_removal(workspace_id)
        and stuffbox.is_workspace_member(workspace_id, auth.uid())
      )
    )
  );

create policy "workspace_members: admin full access"
  on stuffbox.workspace_members for all
  using (stuffbox.requesting_user_is_admin())
  with check (stuffbox.requesting_user_is_admin());

-- workspace_invites (no public select — a stranger following a link isn't a
-- member yet; the read-only landing and the join both go through the
-- security-definer RPCs below, which expose only the single row for the
-- exact token supplied, never the table). Deleting an invite is owner-only
-- no matter what; creating one can be relaxed to regular members via
-- collaborationSettings.allowMemberInvites.
create policy "workspace_invites: member select"
  on stuffbox.workspace_invites for select
  using (stuffbox.is_workspace_member(workspace_id, auth.uid()));

create policy "workspace_invites: owner or allowed member insert"
  on stuffbox.workspace_invites for insert
  with check (
    stuffbox.is_workspace_member(workspace_id, auth.uid())
    and (
      exists (
        select 1 from stuffbox.workspaces w
        where w.id = workspace_id and w.owner_id = auth.uid()
      )
      or stuffbox.workspace_allows_member_invites(workspace_id)
    )
  );

create policy "workspace_invites: owner delete"
  on stuffbox.workspace_invites for delete
  using (
    exists (
      select 1 from stuffbox.workspaces w
      where w.id = workspace_id and w.owner_id = auth.uid()
    )
  );

create policy "workspace_invites: admin full access"
  on stuffbox.workspace_invites for all
  using (stuffbox.requesting_user_is_admin())
  with check (stuffbox.requesting_user_is_admin());

